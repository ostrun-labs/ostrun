using System.Text;

namespace OstrunGenerator;

// Generates the README.md of the generated app: how to start and stop it, the
// public prefix and health URL of each selected service, the Mailpit URL when
// the app has one, and a warning about dev values. Everything comes from
// app.json and the manifests, so no service is special-cased by name.
public static class ReadmeGenerator
{
    public static string Generate(AppConfig app, IReadOnlyList<ResolvedService> services, Values values, bool prod)
    {
        var gateway = $"http://localhost:{values.Items["GATEWAY_PORT"]}";
        var sb = new StringBuilder();

        sb.AppendLine($"# {app.App}");
        sb.AppendLine();
        sb.AppendLine("Generated by [Ostrun](https://github.com/ostrun-labs/ostrun). Once generated, this repo stands alone.");
        sb.AppendLine();
        sb.AppendLine("## Run it");
        sb.AppendLine();
        sb.AppendLine("```bash");
        if (prod)
        {
            sb.AppendLine("cp .env.example .env   # then replace every change-me");
        }
        sb.AppendLine("docker compose up --build -d");
        sb.AppendLine("docker compose down");
        sb.AppendLine("```");
        sb.AppendLine();
        sb.AppendLine(prod
            ? "The first command builds and starts the app, the second stops it. Compose refuses to start until `.env` has a value for every variable."
            : "The first command builds and starts the app, the second stops it. No `.env` is needed: the dev values are the defaults in `docker-compose.yml`.");
        sb.AppendLine();
        sb.AppendLine($"Everything goes through the gateway at {gateway}.");
        sb.AppendLine();
        sb.AppendLine("## Services");

        foreach (var svc in services)
        {
            var key = svc.ServiceKey;
            var m = svc.Manifest;
            var name = string.IsNullOrEmpty(m.DisplayName) ? svc.Ref.Ref : m.DisplayName;
            sb.AppendLine();
            sb.AppendLine($"### {name}");
            sb.AppendLine();
            if (!string.IsNullOrEmpty(m.Description))
            {
                sb.AppendLine(m.Description);
                sb.AppendLine();
            }
            sb.AppendLine($"- Public prefix: {gateway}/{key}/");
            sb.AppendLine($"- Health: {gateway}/{key}{m.HealthCheck.Path}");
            if (!string.IsNullOrEmpty(svc.Repository))
            {
                sb.AppendLine($"- Routes and configuration: see the README of {svc.Repository}.");
            }
        }

        if (values.Items.TryGetValue(DevValues.MailpitPortVar, out var mailpitPort))
        {
            sb.AppendLine();
            sb.AppendLine("## Emails");
            sb.AppendLine();
            sb.AppendLine($"Emails sent by the app land in Mailpit, not in a real inbox: http://localhost:{mailpitPort}");
        }

        sb.AppendLine();
        sb.AppendLine("## Before deploying");
        sb.AppendLine();
        if (prod)
        {
            sb.AppendLine("This app was generated with `--prod`: no secret is written in this repo. Keep `.env` out of git (it is already in `.gitignore`).");
        }
        else
        {
            sb.AppendLine("The dev values are written in `docker-compose.yml` and `.env.example`, so they are in this repo. Don't deploy this app as it is.");
            sb.AppendLine();
            sb.AppendLine("Regenerate it with `--prod` and fill in `.env` with real values. If this repo is public and you deploy it in dev mode, anyone can read the signing key and forge tokens.");
        }

        return sb.ToString();
    }
}
