using System.Text;

namespace OstrunGenerator;

public static class EnvExampleGenerator
{
    public static string Generate(AppConfig app, IReadOnlyList<ResolvedService> services, bool eventBusNeeded, Values values, bool prod = false)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# GENERATED by ostrun/generator from {app.App}.app.json + services/*/ostrun.manifest.json — do not edit, regenerate instead.");
        if (prod)
        {
            sb.AppendLine("# Generated with --prod: docker-compose.yml has no defaults, except for variables");
            sb.AppendLine("# with a default in their manifest. Copy this file to .env and replace every");
            sb.AppendLine($"# {DevValues.Placeholder} before `docker compose up`. .env is gitignored.");
        }
        else
        {
            sb.AppendLine("# These are dev values: docker-compose.yml already uses them as defaults, so the");
            sb.AppendLine("# app runs without a .env. Copy this file to .env to override any of them.");
            sb.AppendLine("# Use --prod when generating, before deploying. .env is gitignored.");
        }
        sb.AppendLine("#");
        sb.AppendLine("# ASPNETCORE_URLS, ConnectionStrings__* and RabbitMq__* are absent on purpose:");
        sb.AppendLine("# they're topology, derived from the manifests and inlined straight into");
        sb.AppendLine("# docker-compose.yml. This file holds credentials and deployment values only.");
        sb.AppendLine();
        sb.AppendLine("# ---- app ----------------------------------------------------------------");
        sb.AppendLine($"GATEWAY_PORT={values.Items["GATEWAY_PORT"]}");
        if (values.Items.TryGetValue(DevValues.MailpitPortVar, out var mailpitPort))
        {
            sb.AppendLine("# Host port of the Mailpit web UI, where the emails sent by the app show up.");
            sb.AppendLine($"{DevValues.MailpitPortVar}={mailpitPort}");
        }
        sb.AppendLine();

        if (eventBusNeeded)
        {
            sb.AppendLine("# RabbitMQ (event bus) — shared by every service in this app.");
            sb.AppendLine($"RABBITMQ_USER={values.Items["RABBITMQ_USER"]}");
            sb.AppendLine($"RABBITMQ_PASSWORD={values.Items["RABBITMQ_PASSWORD"]}");
            sb.AppendLine();
        }

        foreach (var svc in services)
        {
            var key = svc.ServiceKey;
            var prefix = Naming.EnvPrefix(key);
            sb.AppendLine($"# ---- {svc.Ref.Ref} ----");

            if (svc.Manifest.NeedsDb)
            {
                sb.AppendLine($"{prefix}POSTGRES_USER={values.Items[$"{prefix}POSTGRES_USER"]}");
                sb.AppendLine($"{prefix}POSTGRES_PASSWORD={values.Items[$"{prefix}POSTGRES_PASSWORD"]}");
                sb.AppendLine($"{prefix}POSTGRES_DB={values.Items[$"{prefix}POSTGRES_DB"]}");
            }

            foreach (var env in svc.Manifest.Env)
            {
                if (DevValues.IsDerived(env.Name))
                {
                    continue;
                }

                var varName = Naming.EnvVar(key, env.Name);
                if (!string.IsNullOrEmpty(env.Description))
                {
                    sb.AppendLine($"# {(env.Required ? "required" : "optional")} — {env.Description}");
                }
                sb.AppendLine($"{varName}={values.Items[varName]}");
            }

            sb.AppendLine();
        }

        return sb.ToString();
    }
}
