using System.Text;

namespace OstrunGenerator;

public static class EnvExampleGenerator
{
    public static string Generate(AppConfig app, IReadOnlyList<ResolvedService> services, bool eventBusNeeded)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# GENERATED by ostrun/generator from {app.App}.app.json + services/*/ostrun.manifest.json — do not edit, regenerate instead.");
        sb.AppendLine("# Copy to .env and fill in every \"change-me\". .env is gitignored.");
        sb.AppendLine("#");
        sb.AppendLine("# ASPNETCORE_URLS, ConnectionStrings__* and RabbitMq__* are absent on purpose:");
        sb.AppendLine("# they're topology, derived from the manifests and inlined straight into");
        sb.AppendLine("# docker-compose.yml. This file holds credentials and deployment values only.");
        sb.AppendLine();
        sb.AppendLine("# ---- app ----------------------------------------------------------------");
        sb.AppendLine($"GATEWAY_PORT={app.GatewayPort}");
        sb.AppendLine();

        if (eventBusNeeded)
        {
            sb.AppendLine("# RabbitMQ (event bus) — shared by every service in this app.");
            sb.AppendLine("RABBITMQ_USER=ostrun");
            sb.AppendLine("RABBITMQ_PASSWORD=change-me");
            sb.AppendLine();
        }

        foreach (var svc in services)
        {
            var key = svc.ServiceKey;
            var prefix = Naming.EnvPrefix(key);
            sb.AppendLine($"# ---- {svc.Ref.Ref} ----");

            if (svc.Manifest.NeedsDb)
            {
                sb.AppendLine($"{prefix}POSTGRES_USER=ostrun_{key}");
                sb.AppendLine($"{prefix}POSTGRES_PASSWORD=change-me");
                sb.AppendLine($"{prefix}POSTGRES_DB=ostrun_{key}");
            }

            foreach (var env in svc.Manifest.Env)
            {
                if (env.Name is "ASPNETCORE_URLS" || env.Name.StartsWith("ConnectionStrings__", StringComparison.Ordinal) || env.Name.StartsWith("RabbitMq__", StringComparison.Ordinal))
                {
                    continue;
                }

                var varName = Naming.EnvVar(key, env.Name);
                if (!string.IsNullOrEmpty(env.Description))
                {
                    sb.AppendLine($"# {(env.Required ? "required" : "optional")} — {env.Description}");
                }
                var value = env.Default ?? (env.Required ? "change-me" : "");
                sb.AppendLine($"{varName}={value}");
            }

            sb.AppendLine();
        }

        return sb.ToString();
    }
}
