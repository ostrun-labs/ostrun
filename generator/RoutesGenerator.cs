using System.Text.Json;
using System.Text.Json.Nodes;

namespace OstrunGenerator;

public static class RoutesGenerator
{
    public static string Generate(IReadOnlyList<ResolvedService> services)
    {
        var routes = new JsonObject();
        var clusters = new JsonObject();

        foreach (var svc in services)
        {
            var key = svc.ServiceKey;
            var port = svc.Manifest.Ports[0].ContainerPort;
            var publicPrefix = "/" + key;
            var basePath = string.IsNullOrEmpty(svc.Manifest.BasePath) ? "/" : svc.Manifest.BasePath;

            var transforms = new JsonArray();
            if (basePath != publicPrefix)
            {
                transforms.Add(new JsonObject { ["PathRemovePrefix"] = publicPrefix });
                if (basePath != "/")
                {
                    transforms.Add(new JsonObject { ["PathPrefix"] = basePath });
                }
            }

            var route = new JsonObject
            {
                ["ClusterId"] = key,
                ["Order"] = 100,
                ["Match"] = new JsonObject { ["Path"] = $"{publicPrefix}/{{**catch-all}}" },
            };
            if (transforms.Count > 0)
            {
                route["Transforms"] = transforms;
            }
            routes[$"{key}-route"] = route;

            // healthCheck.path is always container-absolute (e.g. "/health"),
            // independent of basePath — a service's health endpoint commonly
            // isn't mounted under its own route group. A dedicated,
            // higher-priority route (lower Order) guarantees it stays
            // reachable even when the catch-all route above forwards the
            // public prefix unchanged (basePath == publicPrefix).
            routes[$"{key}-health"] = new JsonObject
            {
                ["ClusterId"] = key,
                ["Order"] = 1,
                ["Match"] = new JsonObject { ["Path"] = $"{publicPrefix}{svc.Manifest.HealthCheck.Path}" },
                ["Transforms"] = new JsonArray
                {
                    new JsonObject { ["PathRemovePrefix"] = publicPrefix },
                },
            };

            clusters[key] = new JsonObject
            {
                ["Destinations"] = new JsonObject
                {
                    [$"{key}-api"] = new JsonObject { ["Address"] = $"http://{key}-api:{port}/" },
                },
                ["HealthCheck"] = new JsonObject
                {
                    ["Active"] = new JsonObject
                    {
                        ["Enabled"] = true,
                        ["Interval"] = "00:00:10",
                        ["Timeout"] = "00:00:05",
                        ["Policy"] = "ConsecutiveFailures",
                        ["Path"] = svc.Manifest.HealthCheck.Path,
                    },
                },
            };
        }

        var root = new JsonObject
        {
            ["//"] = "GENERATED by ostrun/generator — do not edit, regenerate instead.",
            ["ReverseProxy"] = new JsonObject
            {
                ["Routes"] = routes,
                ["Clusters"] = clusters,
            },
        };

        return root.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
    }
}
