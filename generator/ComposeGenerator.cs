using System.Text;

namespace OstrunGenerator;

public static class ComposeGenerator
{
    public static string Generate(AppConfig app, IReadOnlyList<ResolvedService> services, bool eventBusNeeded, IReadOnlyDictionary<string, string> values)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# GENERATED by ostrun/generator from {app.App}.app.json — do not edit, regenerate instead.");
        sb.AppendLine();
        sb.AppendLine($"name: {app.App}");
        sb.AppendLine();
        sb.AppendLine("services:");
        sb.AppendLine();

        foreach (var svc in services)
        {
            AppendService(sb, svc, eventBusNeeded, values);
        }

        if (eventBusNeeded)
        {
            AppendRabbitMq(sb, values);
        }

        AppendGateway(sb, services, values);

        // Compose rejects a bare "volumes:" key, so it is only written when a DB needs one.
        var dbServices = services.Where(s => s.Manifest.NeedsDb).ToList();
        if (dbServices.Count > 0)
        {
            sb.AppendLine("volumes:");
            foreach (var svc in dbServices)
            {
                sb.AppendLine($"  {svc.ServiceKey}-db-data:");
            }
            sb.AppendLine();
        }

        return sb.ToString();
    }

    private static void AppendService(StringBuilder sb, ResolvedService svc, bool eventBusNeeded, IReadOnlyDictionary<string, string> values)
    {
        var key = svc.ServiceKey;
        var prefix = Naming.EnvPrefix(key);
        var port = svc.Manifest.Ports[0].ContainerPort;

        if (svc.Manifest.NeedsDb)
        {
            sb.AppendLine($"  {key}-db:");
            sb.AppendLine("    image: postgres:16-alpine");
            sb.AppendLine("    environment:");
            sb.AppendLine($"      POSTGRES_USER: {Var(values, $"{prefix}POSTGRES_USER")}");
            sb.AppendLine($"      POSTGRES_PASSWORD: {Var(values, $"{prefix}POSTGRES_PASSWORD")}");
            sb.AppendLine($"      POSTGRES_DB: {Var(values, $"{prefix}POSTGRES_DB")}");
            sb.AppendLine("    volumes:");
            sb.AppendLine($"      - {key}-db-data:/var/lib/postgresql/data");
            sb.AppendLine("    healthcheck:");
            sb.AppendLine($"      test: [\"CMD-SHELL\", \"pg_isready -U {Var(values, $"{prefix}POSTGRES_USER")} -d {Var(values, $"{prefix}POSTGRES_DB")}\"]");
            sb.AppendLine("      interval: 5s");
            sb.AppendLine("      timeout: 5s");
            sb.AppendLine("      retries: 5");
            sb.AppendLine();
        }

        sb.AppendLine($"  {key}-api:");
        sb.AppendLine("    build:");
        sb.AppendLine($"      context: ./services/{svc.Ref.Ref}");
        sb.AppendLine("      dockerfile: Dockerfile");
        sb.AppendLine("    environment:");
        sb.AppendLine($"      ASPNETCORE_URLS: http://+:{port}");

        foreach (var env in svc.Manifest.Env)
        {
            if (env.Name == "ASPNETCORE_URLS")
            {
                continue; // already derived above
            }

            if (env.Name.StartsWith("ConnectionStrings__", StringComparison.Ordinal))
            {
                sb.AppendLine($"      {env.Name}: Host={key}-db;Port=5432;Database={Var(values, $"{prefix}POSTGRES_DB")};Username={Var(values, $"{prefix}POSTGRES_USER")};Password={Var(values, $"{prefix}POSTGRES_PASSWORD")}");
                continue;
            }

            if (env.Name.StartsWith("RabbitMq__", StringComparison.Ordinal))
            {
                // Derived below as a block, once, rather than per-variable —
                // skip individual RabbitMq__* entries here.
                continue;
            }

            sb.AppendLine($"      {env.Name}: {Var(values, Naming.EnvVar(key, env.Name))}");
        }

        if (eventBusNeeded && svc.Manifest.Env.Any(e => e.Name.StartsWith("RabbitMq__", StringComparison.Ordinal)))
        {
            sb.AppendLine("      RabbitMq__Host: rabbitmq");
            sb.AppendLine("      RabbitMq__VirtualHost: /");
            sb.AppendLine($"      RabbitMq__Username: {Var(values, "RABBITMQ_USER")}");
            sb.AppendLine($"      RabbitMq__Password: {Var(values, "RABBITMQ_PASSWORD")}");
        }

        var dependsOn = new List<string>();
        if (svc.Manifest.NeedsDb) dependsOn.Add($"{key}-db");
        if (eventBusNeeded && svc.Manifest.Env.Any(e => e.Name.StartsWith("RabbitMq__", StringComparison.Ordinal))) dependsOn.Add("rabbitmq");

        if (dependsOn.Count > 0)
        {
            sb.AppendLine("    depends_on:");
            foreach (var dep in dependsOn)
            {
                sb.AppendLine($"      {dep}:");
                sb.AppendLine("        condition: service_healthy");
            }
        }

        sb.AppendLine();
    }

    // Every variable carries its dev value, so `docker compose up` needs no
    // .env. ":-" also covers a variable that is present but empty: Compose
    // would pass "" and a .NET service can't bind that to an int or bool.
    private static string Var(IReadOnlyDictionary<string, string> values, string name) => $"${{{name}:-{values[name]}}}";

    private static void AppendRabbitMq(StringBuilder sb, IReadOnlyDictionary<string, string> values)
    {
        sb.AppendLine("  rabbitmq:");
        sb.AppendLine("    image: rabbitmq:3.13-management-alpine");
        sb.AppendLine("    environment:");
        sb.AppendLine($"      RABBITMQ_DEFAULT_USER: {Var(values, "RABBITMQ_USER")}");
        sb.AppendLine($"      RABBITMQ_DEFAULT_PASS: {Var(values, "RABBITMQ_PASSWORD")}");
        sb.AppendLine("    healthcheck:");
        sb.AppendLine("      test: [\"CMD\", \"rabbitmq-diagnostics\", \"-q\", \"ping\"]");
        sb.AppendLine("      interval: 5s");
        sb.AppendLine("      timeout: 5s");
        sb.AppendLine("      retries: 10");
        sb.AppendLine();
    }

    private static void AppendGateway(StringBuilder sb, IReadOnlyList<ResolvedService> services, IReadOnlyDictionary<string, string> values)
    {
        sb.AppendLine("  gateway:");
        sb.AppendLine("    build:");
        sb.AppendLine("      context: ./gateway");
        sb.AppendLine("      dockerfile: Dockerfile");
        sb.AppendLine("    environment:");
        sb.AppendLine("      ASPNETCORE_URLS: http://+:8080");
        sb.AppendLine("    ports:");
        sb.AppendLine($"      - \"{Var(values, "GATEWAY_PORT")}:8080\"");
        sb.AppendLine("    volumes:");
        sb.AppendLine("      - ./gateway/routes.generated.json:/app/routes.generated.json:ro");
        sb.AppendLine("    depends_on:");
        foreach (var svc in services)
        {
            sb.AppendLine($"      - {svc.ServiceKey}-api");
        }
        sb.AppendLine();
    }
}
